/**
 * SDK Surface Schema — Single source of truth for all prvctice.* methods.
 *
 * Every public method in the SDK is declared here. Downstream consumers
 * (appReviewer allowlist, available connectors list, API docs) derive their
 * data from this schema via helper exports at the bottom of this file.
 *
 * To add a new SDK method: add an entry here. That's it.
 */

// ---------------------------------------------------------------------------
// SDK Version — bump when the SDK surface changes
// ---------------------------------------------------------------------------

/** Semantic version of the SDK contract. Sent in bridge handshake. */
export const SDK_VERSION = '3.0.0';

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type TransportMode =
  | 'local' // runs in iframe, no postMessage
  | 'bridge' // _request() round-trip
  | 'connector' // _request() with connector:request type
  | 'callback' // registers a callback, returns unsubscribe
  | 'fire-and-forget' // _send() without waiting
  | 'custom'; // special handling (e.g. download listener)

export interface SdkMethod {
  readonly namespace: string; // '' for top-level, 'storage', 'ai', etc.
  readonly method: string; // 'get', 'complete', etc.
  readonly params: string; // e.g. '(key: string)' — documentation only
  readonly returns: string; // e.g. 'Promise<any>' — documentation only
  readonly transport: TransportMode;
  readonly source: string; // 'bridgeSDK' | 'audio.js' | 'math.js' | etc.
  readonly since: string; // version when added: '1.0', '2.0', '2.1'
  readonly deprecated?: string; // version when deprecated
  readonly connector?: string; // backend connector ID if transport is 'connector'
}

export interface SdkConnector {
  readonly id: string; // 'weather', 'web-fetch', 'media-tools'
  readonly sdkNamespace: string; // 'weather', 'web', 'media'
  readonly requiresKey?: string; // key name: 'tmdb', 'youtube', 'discogs'
  readonly since: string;
}

