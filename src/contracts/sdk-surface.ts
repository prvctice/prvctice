/**
 * Full method path: 'prvctice.namespace.method' or 'prvctice.method' for top-level.
 */
function methodPath(m: SdkMethod): string {
  return m.namespace ? `prvctice.${m.namespace}.${m.method}` : `prvctice.${m.method}`;
}

/** All valid prvctice.* method paths as a Set (for appReviewer allowlist). */
let _validNamespacesCache: ReadonlySet<string> | null = null;
export function getValidNamespaces(): ReadonlySet<string> {
  if (_validNamespacesCache) return _validNamespacesCache;
  _validNamespacesCache = new Set(SDK_METHODS.map(methodPath));
  return _validNamespacesCache;
}

/** Connectors available without API keys (for useAppGenerator BASE_CONNECTORS). */
export function getBaseConnectors(): readonly string[] {
  return SDK_CONNECTORS.filter((c) => !c.requiresKey).map((c) => c.id);
}

/** Connectors requiring user-provided API keys (for useAppGenerator KEY_GATED_CONNECTORS). */
export function getKeyGatedConnectors(): ReadonlyArray<{
  readonly connector: string;
  readonly key: string;
}> {
  return SDK_CONNECTORS.filter((c) => c.requiresKey).map((c) => ({
    connector: c.id,
    key: c.requiresKey!,
  }));
}

/**
 * Map a hyphenated connector ID to its valid JS namespace name.
 * E.g., 'media-tools' -> 'media', 'google-books' -> 'googleBooks'.
 */
export function connectorSdkNamespace(connectorId: string): string {
  const entry = SDK_CONNECTORS.find((c) => c.id === connectorId);
  if (entry) return entry.sdkNamespace;
  // Fallback: camelCase the ID
  return connectorId.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
}
